import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {performance} from 'node:perf_hooks';
import ts from 'typescript';
const filename = new URL('../app/charts/relativeVolume.ts', import.meta.url);
const module = {exports: {}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(filename, 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022}}).outputText, {exports: module.exports, module});
const {computeRelativeVolume} = module.exports;
const at = (day, hm = '09:15') => Date.parse(`${day}T${hm}:00+05:30`) / 1000;
const bar = (day, volume, hm) => ({time: at(day, hm), volume});
const close = (actual, expected) => assert.ok(Math.abs(actual - expected) < 1e-10, `${actual} != ${expected}`);
const initial = [bar('2026-10-14',100),bar('2026-10-15',200),bar('2026-10-16',450)];
let result = computeRelativeVolume(initial);
assert.equal(result.get(initial[0].time).value, null);
assert.equal(result.get(initial[0].time).samples, 0);
close(result.get(initial[2].time).value, 3);
assert.equal(result.get(initial[2].time).samples, 2);
// Same-slot denominators, unordered input and live revisions.
const mixed = [bar('2026-10-15',40,'09:20'),bar('2026-10-14',10,'09:20'),...initial,bar('2026-10-16',50,'09:20')];
close(computeRelativeVolume(mixed.reverse()).get(at('2026-10-16','09:20')).value,2);
const revisions = computeRelativeVolume([...initial,bar('2026-10-16',600)]);
close(revisions.get(at('2026-10-16')).value,4);
assert.equal(revisions.get(at('2026-10-16')).samples,2);
// Future days/today's later slots cannot change earlier results.
const expanded = computeRelativeVolume([...initial,bar('2026-10-16',9999,'10:00'),bar('2026-10-19',9999)]);
for (const b of initial) assert.deepEqual(expanded.get(b.time),computeRelativeVolume(initial).get(b.time));
const holiday = computeRelativeVolume([bar('2026-10-16',100),bar('2026-10-19',200),bar('2026-10-21',300)]);
close(holiday.get(at('2026-10-21')).value,2);
assert.equal(holiday.get(at('2026-10-21')).samples,2);
// Missing slots consume the window; do not pull in older sessions.
const missing = computeRelativeVolume([bar('2026-10-13',100),bar('2026-10-14',200),bar('2026-10-15',1,'09:20'),bar('2026-10-16',400)],2);
assert.equal(missing.get(at('2026-10-16')).samples,1);
close(missing.get(at('2026-10-16')).value,2);
const invalid = computeRelativeVolume([bar('2026-10-14',0),bar('2026-10-15',0),bar('2026-10-16',100),bar('2026-10-19',-1),bar('2026-10-21',NaN)]);
assert.equal(invalid.get(at('2026-10-16')).value,null);
assert.equal(invalid.get(at('2026-10-16')).samples,2);
assert.equal(invalid.get(at('2026-10-19')).value,null);
assert.equal(invalid.get(at('2026-10-21')).value,null);
assert.equal(computeRelativeVolume([...initial,bar('2026-10-16',NaN)]).get(at('2026-10-16')).value,null);
assert.equal(computeRelativeVolume([{time:NaN,volume:100}]).size,0);
const days = Array.from({length:22},(_,i)=>new Date(Date.UTC(2026,8,1+i)).toISOString().slice(0,10));
const long = days.map((day,i)=>bar(day,i+1));
result=computeRelativeVolume(long);
assert.equal(result.get(long[21].time).samples,20);
close(result.get(long[21].time).value,22/11.5);
const daily = [{time:Date.UTC(2026,9,14)/1000,volume:100},{time:Date.UTC(2026,9,15)/1000,volume:200}];
close(computeRelativeVolume(daily).get(daily[1].time).value,2);
const workload=days.slice(0,20).flatMap((day,i)=>Array.from({length:75},(_,j)=>({time:at(day)+j*300,volume:(i+1)*(j+1)*100})));
const start=performance.now();for(let i=0;i<400;i++)computeRelativeVolume(workload);
console.log(`PASS: RVOL causal/same-slot/window/revision/missing/zero/daily checks; 1500 bars ${(performance.now()-start)/400} ms per calculation`);
