import fs from 'node:fs';
import assert from 'node:assert/strict';
const base = process.env.AUTH_TEST_URL ?? 'http://127.0.0.1:3002';
const password = fs.readFileSync('.private/login-credentials.txt', 'utf8').split('\n')[1];
const request = (path, init = {}) => fetch(base + path, { ...init, redirect: 'manual' });
const login = (password, next = '/rusty?date=2026-10-01', origin = base) => request('/api/auth/login', { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json' }, body: JSON.stringify({ password, next }) });
const anonymous = await request('/rusty?date=2026-10-01');
assert.equal(anonymous.status,307); assert.match(anonymous.headers.get('location'), /\/login\?next=/);
for (const folder of fs.readdirSync('app/api').filter(x=>x!=='auth')) {
  const route = fs.readFileSync(`app/api/${folder}/route.ts`, 'utf8');
  assert.match(route,/await requireApiSession\(/);
  const method = /export async function POST/.test(route) ? 'POST' : 'GET';
  const response = await request(`/api/${folder}`, { method });
  assert.equal(response.status,401,folder);
}
assert.equal((await login('wrong')).status,401);
assert.equal((await login(password,'/rusty','https://foreign.invalid')).status,403);
const good = await login(password);
assert.equal(good.status,200);
assert.equal((await good.json()).next,'/rusty?date=2026-10-01');
const rawCookie = good.headers.get('set-cookie');
assert.match(rawCookie,/HttpOnly/i); assert.match(rawCookie,/Secure/i); assert.match(rawCookie,/SameSite=lax/i);
const cookie = rawCookie.split(';')[0];
const authenticated = await request('/rusty?date=2026-10-01',{headers:{Cookie:cookie}});
assert.equal(authenticated.status,200);
const html = await authenticated.text();
assert.match(html,/Sign out/); assert.doesNotMatch(html,/Please sign in/);
const data = await request('/api/panther-signals?date=2026-10-01&sources=rusty',{headers:{Cookie:cookie}});
assert.equal(data.status,200); const json=await data.json();
assert.ok(JSON.stringify(json).length>1000,'Authenticated data should load');
const forged = cookie.slice(0,-1)+(cookie.endsWith('a')?'b':'a');
assert.equal((await request('/api/radar',{headers:{Cookie:forged}})).status,401);
const logout = await request('/api/auth/logout',{method:'POST',headers:{Cookie:cookie,Origin:base}});
assert.equal(logout.status,303); assert.match(logout.headers.get('set-cookie'),/Max-Age=0/i);
const externalNext = await login(password,'//foreign.invalid');
assert.equal((await externalNext.json()).next,'/rusty');
for(let i=0;i<5;i++) assert.equal((await login('wrong')).status,401);
assert.equal((await login('wrong')).status,429);
console.log('PASS: all 15 API routes blocked anonymously; login/origin/cookie/tamper/logout/redirect/backoff checks; authenticated Rusty and API data load. No secrets printed.');
